import * as path from 'path';
import { DependencyGraph } from '../graph/dependencyGraph';
import type { CodeFileRecord } from '../model';
import type { AtlasStore } from '../storage/atlasStore';

export interface ProjectMapOptions {
  /** Cap on files listed in the directory section, to keep the document readable. */
  maxFiles?: number;
}

/**
 * Builds an AI-free markdown map of the project: stats, hubs, entry points, docs and a
 * per-folder file listing. Doubles as an "ATLAS.md" context file to paste into AI editors.
 */
export function buildProjectMap(store: AtlasStore, workspaceRoot: string, options: ProjectMapOptions = {}): string {
  const maxFiles = options.maxFiles ?? 400;
  const files = store.listFiles(workspaceRoot);
  const code = store.listCodeFiles(workspaceRoot);
  const docs = store.listDocs(workspaceRoot);
  const stats = store.getStats(workspaceRoot);
  const graph = DependencyGraph.build(workspaceRoot, code);
  const relativeByPath = new Map(files.map((file) => [file.absolutePath, file.relativePath]));
  const rel = (absolutePath: string) => relativeByPath.get(absolutePath) ?? absolutePath;

  const totalLines = code.reduce((sum, file) => sum + file.linesOfCode, 0);
  const componentCount = code.reduce((sum, file) => sum + file.components.length, 0);
  const edgeCount = Array.from(graph.imports.values()).reduce((sum, targets) => sum + targets.length, 0);

  const lines: string[] = [
    `# Atlas: ${path.basename(workspaceRoot)}`,
    '',
    `> Generated by Sandbox Atlas${stats.lastScanAt ? ` from the index of ${new Date(stats.lastScanAt).toISOString().slice(0, 16).replace('T', ' ')}` : ''}. `
    + 'Paste this file into an AI chat to give it a map of the repository.',
    '',
    '## Overview',
    '',
    '| Metric | Value |',
    '| --- | --- |',
    `| Indexed files | ${files.length} |`,
    `| Code files | ${code.length} (${totalLines.toLocaleString('en-US')} non-blank lines) |`,
    `| React components | ${componentCount} |`,
    `| Local import edges | ${edgeCount} |`,
    `| Documentation files | ${docs.length} |`,
    '',
  ];

  const hubs = graph.hubs(10).filter((hub) => hub.dependents > 1);
  if (hubs.length > 0) {
    lines.push('## Hubs (most imported — change with care)', '');
    hubs.forEach((hub) => lines.push(`- \`${rel(hub.file)}\` — imported by ${hub.dependents} files`));
    lines.push('');
  }

  const entryPoints = graph.entryPoints(10);
  if (entryPoints.length > 0) {
    lines.push('## Likely entry points (import others, imported by none)', '');
    entryPoints.forEach((file) => lines.push(`- \`${rel(file)}\``));
    lines.push('');
  }

  if (docs.length > 0) {
    lines.push('## Documentation', '');
    docs.slice(0, 20).forEach((doc) => {
      const tags = [doc.hasSetupGuide && 'setup', doc.hasArchitectureNotes && 'architecture', doc.hasChangelog && 'changelog']
        .filter(Boolean).join(', ');
      const firstHeading = doc.sections[0]?.title;
      lines.push(`- \`${doc.relativePath}\`${firstHeading ? ` — ${firstHeading}` : ''}${tags ? ` _(${tags})_` : ''}`);
    });
    lines.push('');
  }

  lines.push('## Files by folder', '');
  const byFolder = new Map<string, CodeFileRecord[]>();
  code.slice(0, maxFiles).forEach((file) => {
    const folder = path.posix.dirname(file.relativePath);
    byFolder.set(folder, [...(byFolder.get(folder) ?? []), file]);
  });

  Array.from(byFolder.keys()).sort().forEach((folder) => {
    lines.push(`### ${folder === '.' ? '(root)' : `${folder}/`}`, '');
    byFolder.get(folder)!.forEach((file) => {
      const summary = summarizeFile(file);
      const dependents = graph.dependentsOf(file.absolutePath).length;
      lines.push(`- \`${path.posix.basename(file.relativePath)}\`${summary ? ` — ${summary}` : ''}${dependents ? ` · ←${dependents}` : ''}`);
    });
    lines.push('');
  });

  if (code.length > maxFiles) {
    lines.push(`_…and ${code.length - maxFiles} more code files._`, '');
  }

  return lines.join('\n');
}

function summarizeFile(file: CodeFileRecord): string {
  const components = file.components.map((component) => `<${component.name}>`);
  const exported = file.functions.filter((fn) => fn.isExported && !file.components.some((c) => c.name === fn.name)).map((fn) => `${fn.name}()`);
  const otherExports = file.exports
    .filter((exportData) => exportData.type !== 'default' && !file.functions.some((fn) => fn.name === exportData.name))
    .map((exportData) => exportData.name);
  const parts = [...components, ...exported, ...otherExports];
  return parts.length > 6 ? `${parts.slice(0, 6).join(', ')}, +${parts.length - 6}` : parts.join(', ');
}
