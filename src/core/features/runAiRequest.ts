import type { AiCompletionResult, AiProvider } from '../ai/aiProvider';
import type { DailyUsage, UsageLimiter } from '../ai/usageLimiter';
import type { AiRequest } from './aiFeatures';

export interface AiRunResult {
  /** Complete markdown document: title, answer, and footer. */
  markdown: string;
  completion: AiCompletionResult;
  usage: DailyUsage;
}

/**
 * Executes a prepared AI request: enforces the daily limit, calls the provider, records usage
 * and renders the answer as markdown. Shared by every host.
 */
export async function runAiRequest(
  request: AiRequest,
  provider: AiProvider,
  limiter: UsageLimiter,
  dailyRequestLimit: number,
  signal?: AbortSignal,
): Promise<AiRunResult> {
  limiter.assertWithinLimit(provider.mode, dailyRequestLimit);

  const completion = await provider.completeChat(
    [
      { role: 'system', content: request.systemPrompt },
      { role: 'user', content: request.userContent },
    ],
    { maxTokens: request.maxTokens, temperature: request.temperature, signal },
  );
  const usage = await limiter.record(completion.totalTokens);

  const markdown = [
    `# ${request.title}`,
    '',
    completion.content.trim(),
    '',
    '---',
    '',
    ...request.footerLines,
    `**Provider:** ${completion.provider} · ${completion.totalTokens.toLocaleString('en-US')} tokens  `,
    '*Generated by Sandbox Atlas — understand the repo before touching the code.*',
    '',
  ].join('\n');

  return { markdown, completion, usage };
}
